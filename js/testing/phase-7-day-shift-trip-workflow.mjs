import fs from 'node:fs'
import assert from 'node:assert/strict'

const read = (p) => fs.readFileSync(p, 'utf8')
const expect = (text, fragment) => assert.ok(text.includes(fragment), `Missing contract fragment: ${fragment}`)

const db = read('src/utils/indexedDB.js')
const repo = read('src/repositories/dayShiftTripRepository.js')
const store = read('src/stores/dayShiftTrip.js')
const work = read('src/views/WorkModuleView.vue')
const app = read('src/App.vue')
const gps = read('src/services/locationService.js')
const movement = read('src/services/movementAccountingService.js')
const notification = read('src/services/tripNotificationService.js')

expect(db, 'CANONICAL_DB_VERSION = 3')
for (const name of ['days', 'trips', 'gps_snapshots']) expect(db, `createObjectStore('${name}'`)
expect(repo, "saveMutation(this.db, record.id,'DAY','CREATE')")
expect(repo, "saveMutation(this.db, record.id,'SHIFT','CREATE')")
expect(repo, "saveMutation(this.db, record.id,'TRIP','CREATE')")
expect(repo, 'businessKm:null')
expect(repo, 'deadKm:null')
expect(repo, "movementReconciliationStatus:'PENDING'")
expect(store, 'isDayOnline')
expect(store, 'isShiftActive')
expect(store, 'isTripActive')
expect(store, 'recordMissedTrip')
expect(store, 'LocationService.startActiveShiftSnapshots')
expect(store, "entityType:'SHIFT'")
expect(store, 'getForEntity(id)')
expect(store, 'captureShiftEndLocation')
expect(store, 'MovementAccountingService.reconcileShiftMovement')
expect(store, 'movementReconciliationStatus:reconciliation.reconciliationStatus')
expect(work, 'End Shift & Reconcile')
expect(work, 'Save Reconciliation & End Shift')
expect(work, 'Shift Reconciliation Complete')
expect(work, 'pendingGarageLocation')
expect(app, 'SHIFT: {{ store.headerShiftStatus }}')
expect(app, 'TRIP: {{ store.headerTripStatus }}')

// Frozen GPS policy: waiting 5–7 min, active trip 7–10 min,
// between trips moving 1–2 min, stationary 5–7 min.
expect(gps, 'WAITING: 7 * 60 * 1000')
expect(gps, 'TRIP_ACTIVE: 9 * 60 * 1000')
expect(gps, 'BETWEEN_TRIPS_MOVING: 2 * 60 * 1000')
expect(gps, 'BETWEEN_TRIPS_STATIONARY: 6 * 60 * 1000')
expect(gps, 'startActiveShiftSnapshots')
expect(gps, 'foregroundServiceType')
expect(movement, 'gpsSnapshots')
expect(movement, 'ROUTED_TRACE')
expect(movement, 'pointsBetween')
expect(notification, 'START_TRIP')
expect(notification, 'END_TRIP')
console.log('Phase 7 Day/Shift/Trip whole-shift GPS and end-of-shift reconciliation contract passed.')
