import assert from 'node:assert/strict';
import {rollingFuelCostPerKm,projectedFuelCostForKm} from '../domain/fuel.js';
import {rolling7DayKm,odometerAnomalyWarning,recoverDanglingShifts} from '../domain/work.js';
import {fixedExpensePerBusinessKm} from '../domain/expenses.js';
import {maintenanceProgress,provisionMaintenance} from '../domain/maintenance.js';
import {applyPrepayment,amortize} from '../domain/loans.js';
import {profitability,tomorrowTarget} from '../domain/dashboard.js';
import {evaluateAlerts} from '../domain/alerts.js';
const ids=['a','b','c','d','e','f'].map(id=>({id,is_deleted:false,is_voided:false}));
const fuel=ids.map((x,i)=>({...x,odometer:i*1000,litres:40,amount_paise:400000,is_full_tank:true}));
assert.equal(rollingFuelCostPerKm(fuel,3).dataConfidenceState,'ACTUAL');
assert.equal(projectedFuelCostForKm(fuel,1000,3).dataConfidenceState,'PROJECTED');
assert.equal(rolling7DayKm([{id:'w1',start_odometer:0,end_odometer:700,end_at:'2026-08-20T10:00:00.000Z',business_date:'2026-08-20'}],'2026-08-20T10:00:00.000Z').value,100);
assert.equal(fixedExpensePerBusinessKm([{id:'f',monthly_amount_paise:100000,effective_from:'2026-01-01T00:00:00.000Z',effective_to:null}],1000,'2026-08-01T00:00:00.000Z').value,100);
const item={id:'m',expected_cost_paise:400000,expected_km_life:40000,expected_time_life_days:null,baseline_odometer:0,baseline_date:null};
assert.equal(maintenanceProgress(item,{odometer:20000,at:'2026-08-01T00:00:00.000Z'}).ratio,.5);
assert.equal(provisionMaintenance(item,{odometer:20000,at:'2026-08-01T00:00:00.000Z'}).value,200000);
assert.equal(applyPrepayment(100000,150000).value.remainingPrincipalPaise,0);
assert.equal(amortize({principal_paise:1000000,annual_rate_percent:12,term_months:12,emi_paise:100000}).dataConfidenceState,'BASELINE');
assert.equal(profitability({revenue:1000000,fuel:100000,maintenanceProvision:50000,fixedOverhead:100000,loanPrincipal:100000,loanInterest:20000,otherBusinessCosts:30000,takeHomeTargetPaise:200000}).value.netProfitPaise,600000);
assert.equal(evaluateAlerts({loanDueDays:2}).value[0].kind,'LOAN_EMI_DUE');
assert.equal(odometerAnomalyWarning(0,1600).warning,true);
assert.equal(recoverDanglingShifts([{id:'d',status:'OPEN',start_at:'2026-08-01T00:00:00.000Z',is_deleted:false}],'2026-08-02T17:00:00.000Z').length,1);
console.log('KFE domain calculations: PASS');
